package io.github.lucaskfp.learnharness.engine.tools

import io.github.lucaskfp.learnharness.engine.AssetSource
import io.github.lucaskfp.learnharness.engine.model.LhJson
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonObject

/** One tool as the model sees it: name, description and JSON Schema, all from upstream. */
@Serializable
data class ToolSpec(val name: String, val description: String, val inputSchema: JsonObject)

@Serializable
private data class ContractFile(val tools: List<ToolSpec>, val texts: ContractTexts)

@Serializable
data class ContractTexts(
    /** The placeholder result of a question call: never persisted, the answer replaces it. */
    val questionPosed: String,
    /** The result synthesized for a question call whose turn was interrupted. */
    val interrupted: String,
    /** The fixed result of an accepted `probe_done`: the assessment is the call's own arguments. */
    val probeDoneAck: String,
    /** The user-role wake that starts the Teacher once the probe has concluded. */
    val probeHandoff: String,
    /** Rides a successful `plan_init` result: from now on every quiz names one of these node ids. */
    val planNodeIdsReminder: String,
    /** The persisted result of a posed problem: the learner's thinking arrives as messages, never as this result. */
    val problemPosed: String,
    /** The result of a `conclude`: the Practitioner closes and ends its Turn, waiting for the go-ahead. */
    val concludeAck: String,
    /** The model-facing text of the learner's Next marker. */
    val nextProblem: String,
    /** The label a thinking submission is prefixed with for the model. */
    val thinkingLabel: String,
)

/**
 * The tool contracts imported from upstream (`assets/upstream/tools.json`, generated by
 * `scripts/export-android-contracts.ts`). Nothing about a tool's name, description or input
 * shape is written by hand on this side.
 */
class ToolContracts(private val tools: Map<String, ToolSpec>, val texts: ContractTexts) {
    fun spec(name: String): ToolSpec = tools[name] ?: error("No imported contract for tool \"$name\"")

    companion object {
        private const val Path = "upstream/tools.json"

        fun load(assets: AssetSource): ToolContracts {
            val file = LhJson.decodeFromString(ContractFile.serializer(), assets.read(Path))
            return ToolContracts(file.tools.associateBy { it.name }, file.texts)
        }
    }
}
